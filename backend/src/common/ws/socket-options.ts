/**
 * 두 게이트웨이(/realtime, /chat)가 쓰는 socket.io 서버 옵션.
 *
 * 네임스페이스가 달라도 같은 포트의 socket.io 서버 하나를 공유하고, 그 서버는 먼저
 * 초기화된 게이트웨이의 옵션으로 만들어진다. 어느 쪽이 먼저 뜨든 값이 같도록 양쪽에서
 * 이 상수를 쓴다.
 *
 * 값은 socket.io 기본값(25s/20s)이다. 한때 결투 무응답 페널티 때문에 10s/10s로 조였던
 * 적이 있는데, 만료(30초) 시점에 소켓 생존을 읽어 청구 여부를 가르느라 끊김이 그 전에
 * 드러나야 했기 때문이다. 그 방식은 두 가지가 어긋났다 — 10s+10s로 조여도 감지 지연이
 * 최대 20초라 창 후반부(T+10s 이후)의 단절은 여전히 놓쳤고, 판정 근거가 전송 계층의
 * 타이밍에 묶여 있었다.
 *
 * 지금은 초대 전달 여부를 emit 시점에 duels.inviteDeliveredAt으로 기록해서 판단한다
 * (duel.entity.ts 참고). 그래서 30초 창의 **끝**에서 소켓 생존을 읽을 일이 없어졌고,
 * 하트비트를 2.5배로 늘려 전 클라이언트의 트래픽과 불안정한 회선의 재연결을 감수할
 * 이유도 없어져 기본값으로 되돌린다.
 *
 * 다만 "핑 주기와 무관해졌다"고 말할 수는 없다. emit 시점의 판단도 결국 socket.connected를
 * 읽고, socket.io는 조용히 끊긴 클라이언트를 pingInterval + pingTimeout(기본 45초)이
 * 지나야 끊긴 것으로 표시한다. 상대가 신청 직전에 터널에 들어갔다면 소켓은 아직 살아
 * 있어 보이고, 초대는 죽은 소켓으로 나가 전달된 것으로 기록된다. 즉 감지 지연은 창의
 * 끝에서 **시작으로 옮겨졌을 뿐** 사라지지 않았다 — 다만 창 전체(30초)가 아니라 신청
 * 시점 한 순간만 걸리므로 노출 면적은 훨씬 작다.
 *
 * 이 잔여 구멍은 전송 계층을 조여서는 닫히지 않는다(10s/10s로도 20초가 남았다). 닫으려면
 * 클라이언트가 초대를 **렌더한 뒤** 보내는 ack가 있어야 하는데, 결투 프론트가 아직 없어
 * 지금 ack를 요구하면 구현 전까지 페널티가 통째로 비활성화된다. 프론트가 붙을 때
 * inviteDeliveredAt을 ack 시점으로 옮기는 것이 다음 단계다.
 */
export const SOCKET_PING_INTERVAL_MS = 25_000;
export const SOCKET_PING_TIMEOUT_MS = 20_000;
