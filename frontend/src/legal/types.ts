/**
 * 가입 시 동의를 받는 법적 문서의 형태.
 *
 * 본문을 i18n locale 파일이 아니라 이 디렉터리에 따로 두는 이유:
 *   1. 조항이 길어 locale 파일에 인라인으로 넣으면 UI 문구와 뒤섞여 관리가 안 된다.
 *      규칙은 "화면에 보이는 라벨은 i18n, 법적 본문은 legal/"이다.
 *   2. version이 본문과 같은 파일에 있어야 한다 — 조항을 고치면서 버전을 안 올리는 실수를
 *      막기 위함이다. 재동의가 필요한지 판단하려면 "어느 버전에 동의했는지"가 남아야 하는데,
 *      이 값이 그 기준이 된다.
 */
export interface LegalDocument {
  /**
   * 개정일(YYYY-MM-DD). **본문을 실질적으로 수정하면 반드시 함께 올린다.**
   * 재동의가 필요한지 판단하는 기준값으로 쓰도록 만든 값이다. 다만 현재는 동의 이력을 서버에
   * 남기지 않는다 — registerUser 페이로드는 {nickname, nationality}뿐이라, 약관이 개정돼도
   * 기존 이용자가 어느 버전에 동의했었는지는 서버 어디에도 남지 않는다. 서버 측 저장은
   * PR #56(`user_consents` 원장)이 구현 중이다 — 이 값이 그대로 그 원장의 `version` 컬럼에
   * 실린다.
   */
  version: string;
  /** 화면에 그대로 렌더링되는 조항 전문. 언어별로 같은 내용을 담는다. */
  body: { ko: string; en: string };
  /**
   * 동의 목록의 체크박스 라벨 i18n 키(`auth.terms.` 뒤에 붙는 부분).
   *
   * 라벨 **문구**는 규칙대로 i18n에 있고, 여기 두는 것은 그 문구를 가리키는 **키**다.
   * 문서와 같은 자리에 둬야 새 문서를 추가할 때 이 매핑을 빠뜨릴 수 없다 — 예전엔
   * 화면(login.tsx)과 테스트가 같은 표를 각자 복사해 들고 있어서, 한쪽만 고쳐도
   * 테스트가 통과했다.
   */
  labelKey: string;
  /** 상세 보기 화면의 제목 i18n 키. 위와 같은 이유로 문서 옆에 둔다. */
  titleKey: string;
}
