/**
 * 가입 시 동의를 받는 법적 문서의 형태.
 *
 * 본문을 i18n locale 파일이 아니라 이 디렉터리에 따로 두는 이유:
 *   1. 조항이 길어 locale 파일에 인라인으로 넣으면 UI 문구와 뒤섞여 관리가 안 된다.
 *      규칙은 "화면에 보이는 라벨은 i18n, 법적 본문은 legal/"이다.
 *   2. version이 본문과 같은 파일에 있어야 한다 — 조항을 고치면서 버전을 안 올리는 실수를
 *      막기 위함이다. 이 값은 동의 이력(어느 버전에 동의했는지)에 그대로 쓰인다.
 */
export interface LegalDocument {
  /**
   * 개정일(YYYY-MM-DD). **본문을 실질적으로 수정하면 반드시 함께 올린다.**
   * 재동의가 필요한지 판단하는 기준값이고, 서버에 동의 이력으로 남는 값이다.
   */
  version: string;
  /** 화면에 그대로 렌더링되는 조항 전문. 언어별로 같은 내용을 담는다. */
  body: { ko: string; en: string };
}
